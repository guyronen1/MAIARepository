# ============================================================
# generate-clean-schema.ps1
# Generates Scripts/schema-clean.sql: the CURRENT schema of a fresh
# MAIA database - tables, keys, indexes, CHECK constraints - plus the
# __EFMigrationsHistory rows, so EF treats the database as fully
# migrated and later upgrades can use `dotnet ef migrations script`.
#
# No data is emitted. Reference data (roles, admin user, scan types,
# job types, error types) lives in Scripts/seed-metadata.sql.
#
# Why not strip the migration script? Replaying 30+ migrations in one
# file breaks whenever a migration's raw SQL references a column a later
# one drops (SQL Server compiles the whole batch). The model DDL is the
# end state directly.
#
# Usage (from Maia.Services root; a running Maia.API locks Debug bin,
# so this builds Release):
#   .\Scripts\generate-clean-schema.ps1
#
# Deploy sequence on a new, empty database:
#   1. schema-clean.sql
#   2. seed-metadata.sql
# (sqlcmd users: pass -I - filtered indexes need QUOTED_IDENTIFIER ON.)
# ============================================================

$ErrorActionPreference = 'Stop'

$projectRoot = $PSScriptRoot | Split-Path -Parent
$cleanFile   = Join-Path $PSScriptRoot 'schema-clean.sql'
$modelFile   = Join-Path ([IO.Path]::GetTempPath()) 'maia-model.sql'
$migrFile    = Join-Path ([IO.Path]::GetTempPath()) 'maia-migrations.sql'
$efArgs      = @('--project', 'Maia.Infrastructure', '--startup-project', 'Maia.API', '--configuration', 'Release')

Push-Location $projectRoot
try {
    Write-Host 'Generating DDL from the current model ...'
    & dotnet ef dbcontext script @efArgs --output $modelFile
    if ($LASTEXITCODE -ne 0) { throw "dotnet ef dbcontext script failed (exit $LASTEXITCODE)" }

    # Only used to harvest the migration IDs + EF product version.
    Write-Host 'Reading migration list ...'
    & dotnet ef migrations script @efArgs --no-build --output $migrFile
    if ($LASTEXITCODE -ne 0) { throw "dotnet ef migrations script failed (exit $LASTEXITCODE)" }
} finally {
    Pop-Location
}

# Drop the HasData seed batches - seed-metadata.sql owns all data.
$batches = [IO.File]::ReadAllText($modelFile) -split '(?m)^GO\r?$'
$ddl = $batches |
    Where-Object { $_.Trim() -ne '' -and $_ -notmatch 'INSERT INTO' } |
    ForEach-Object { $_.Trim() + "`r`nGO" }

$history = [regex]::Matches([IO.File]::ReadAllText($migrFile),
    "INSERT INTO \[__EFMigrationsHistory\] \(\[MigrationId\], \[ProductVersion\]\)\s*VALUES \(N'([^']+)', N'([^']+)'\)")
if ($history.Count -eq 0) { throw 'No migrations found in the migration script.' }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("-- MAIA schema-clean.sql - generated by Scripts/generate-clean-schema.ps1 on $(Get-Date -Format 'yyyy-MM-dd').")
[void]$sb.AppendLine("-- Current schema for a NEW, EMPTY database. Run seed-metadata.sql next.")
[void]$sb.AppendLine("-- Latest migration: $($history[$history.Count - 1].Groups[1].Value)")
[void]$sb.AppendLine('-- sqlcmd users: pass -I (filtered indexes need QUOTED_IDENTIFIER ON).')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('SET QUOTED_IDENTIFIER ON;')
[void]$sb.AppendLine('SET ANSI_NULLS ON;')
[void]$sb.AppendLine('GO')
[void]$sb.AppendLine('')
foreach ($b in $ddl) { [void]$sb.AppendLine($b); [void]$sb.AppendLine('') }

# CHECK constraints are raw SQL in migration AddCompositeInvariantCheckConstraints
# (not in the model), so dbcontext script doesn't emit them. Keep in sync.
[void]$sb.AppendLine(@'
-- Composite fix-policy invariants (migration AddCompositeInvariantCheckConstraints)
ALTER TABLE [dbo].[FixPolicyRuleSteps] WITH CHECK
    ADD CONSTRAINT [CK_FixPolicyRuleSteps_ActionType_NotManualOrComposite]
    CHECK ([ActionType] NOT IN ('Manual', 'Composite'));
ALTER TABLE [dbo].[FixPolicyRuleSteps] WITH CHECK
    ADD CONSTRAINT [CK_FixPolicyRuleSteps_ActionPayload_NotEmpty]
    CHECK (LEN(LTRIM(RTRIM([ActionPayload]))) > 0);
ALTER TABLE [dbo].[FixPolicyRules] WITH CHECK
    ADD CONSTRAINT [CK_FixPolicyRules_CompositeHeader_NullPayload]
    CHECK ([ActionType] <> 'Composite' OR [ActionPayload] IS NULL);
GO

-- Composite scan-rule condition kinds (migration AddScanCheckRuleConditions)
ALTER TABLE [dbo].[ScanCheckRuleConditions] WITH CHECK
    ADD CONSTRAINT [CK_ScanCheckRuleConditions_Kind_Allowed]
    CHECK ([Kind] IN ('ValueEquals', 'ColumnRange', 'FileContent', 'ErrorKeyword'));
GO

-- Mark every migration as applied so future upgrades are plain EF scripts.
CREATE TABLE [__EFMigrationsHistory] (
    [MigrationId] nvarchar(150) NOT NULL,
    [ProductVersion] nvarchar(32) NOT NULL,
    CONSTRAINT [PK___EFMigrationsHistory] PRIMARY KEY ([MigrationId])
);
GO
'@)
[void]$sb.AppendLine('INSERT INTO [__EFMigrationsHistory] ([MigrationId], [ProductVersion]) VALUES')
$rows = foreach ($m in $history) { "    (N'$($m.Groups[1].Value)', N'$($m.Groups[2].Value)')" }
[void]$sb.AppendLine(($rows -join ",`r`n") + ';')
[void]$sb.AppendLine('GO')

[IO.File]::WriteAllText($cleanFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($true))
Remove-Item $modelFile, $migrFile -ErrorAction SilentlyContinue
Write-Host "Done. schema-clean.sql written ($($history.Count) migrations marked applied)."
